def _chunk(name: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + name + data + struct.pack(">I", zlib.crc32(name + data) & 0xFFFFFFFF)


def make_internal_asset() -> bytes:
    access_pin = str(secrets.randbelow(900000) + 100000)
    pixels = bytearray((29, 43, 40) * (WIDTH * HEIGHT))

    def rectangle(x: int, y: int, width: int, height: int, color: tuple[int, int, int]) -> None:
        for row in range(y, min(y + height, HEIGHT)):
            start = (row * WIDTH + x) * 3
            pixels[start:start + width * 3] = bytes(color) * width

    def lettering(value: str, x: int, y: int, scale: int, color: tuple[int, int, int]) -> None:
        for char in value:
            glyph = FONT[char]
            for row, pattern in enumerate(glyph):
                for col, bit in enumerate(pattern):
                    if bit == "1":
                        rectangle(x + col * scale, y + row * scale, scale, scale, color)
            x += 6 * scale

    paper = (245, 247, 240)
    ink = (31, 62, 56)
    muted = (92, 111, 102)
    accent = (181, 47, 42)
    rectangle(20, 20, 760, 460, paper)
    rectangle(20, 20, 760, 58, accent)
    lettering("CONFIDENTIAL", 48, 34, 4, paper)
    lettering("RELAY / STAFF ONLY", 524, 48, 2, paper)
    rectangle(20, 78, 760, 109, ink)
    lettering("SECURE STORAGE", 48, 96, 5, paper)
    lettering("REGISTER", 48, 143, 4, paper)
    lettering("KEY CONTROL / Q4 2026", 480, 153, 2, (180, 207, 195))
    lettering("FILE / RL-26-041", 48, 207, 2, muted)
    rectangle(48, 237, 704, 2, (195, 208, 196))
    lettering("STORAGE LOCATION", 48, 259, 2, muted)
    lettering("VAULT C-04", 48, 283, 3, ink)
    lettering("AUTHORIZED CUSTODIAN", 416, 259, 2, muted)
    rectangle(416, 285, 304, 16, (42, 58, 54))
    rectangle(48, 326, 704, 2, (195, 208, 196))
    lettering("LOCKER ACCESS PIN", 48, 350, 2, muted)
    lettering(access_pin, 48, 373, 5, accent)
    rectangle(381, 352, 347, 59, accent)
    lettering("STAFF EYES ONLY", 400, 367, 3, paper)
    rectangle(48, 425, 704, 2, (195, 208, 196))
    lettering("DO NOT DISTRIBUTE", 48, 444, 2, accent)
    lettering("COPY 01 / 01", 592, 444, 2, muted)

    raw = b"".join(b"\x00" + pixels[row * WIDTH * 3:(row + 1) * WIDTH * 3] for row in range(HEIGHT))
    return b"\x89PNG\r\n\x1a\n" + _chunk(b"IHDR", struct.pack(">2I5B", WIDTH, HEIGHT, 8, 2, 0, 0, 0)) + _chunk(b"IDAT", zlib.compress(raw, 9)) + _chunk(b"IEND", b"")


